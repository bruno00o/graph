import { describe, expect, it } from 'vitest'
import { DirtyRange, noPaint, StateBuffers, stateRow } from './state-buffers'

describe('DirtyRange', () => {
  it('tracks the smallest range and resets on take', () => {
    const range = new DirtyRange()
    expect(range.take()).toBeNull()
    range.add(7)
    range.add(2)
    range.add(5)
    expect(range.take()).toEqual([2, 7])
    expect(range.take()).toBeNull()
  })
})

describe('StateBuffers', () => {
  it('marks only changed masks as dirty', () => {
    const states = new StateBuffers()
    states.reserve(4, 4)
    states.setNode(2, 0b1)
    states.setNode(2, 0b1)
    states.setEdge(3, 0b10)
    expect(states.nodeMask[2]).toBe(1)
    expect(states.nodeDirty.take()).toEqual([2, 2])
    expect(states.edgeDirty.take()).toEqual([3, 3])
    states.setNode(2, 0b1)
    expect(states.nodeDirty.take()).toBeNull()
  })

  it('grows masks past the reserved capacity', () => {
    const states = new StateBuffers()
    states.setNode(100, 0x80000000)
    expect(states.nodeMask[100]).toBe(0x80000000)
  })

  it('writes a style row and clears it with null', () => {
    const states = new StateBuffers()
    const version = states.tableVersion
    states.setStyle('nodes', 3, { opacity: 0.4, halo: true, label: false, stroke: 9 })
    expect(Array.from(states.numbers.subarray(12, 16))).toEqual([expect.closeTo(0.4, 5), -1, 1, 0])
    expect(states.paint[12]).toBe(noPaint)
    expect(states.paint[13]).toBe(9)
    expect(states.labelFlags[3]).toBe(0)
    expect(states.tableVersion).toBe(version + 1)
    states.setStyle('nodes', 3, null)
    expect(Array.from(states.numbers.subarray(12, 16))).toEqual([-1, -1, -1, -1])
    expect(states.paint[13]).toBe(noPaint)
    expect(states.labelFlags[3]).toBe(-1)
  })

  it('packs the outline color and its width as float bits', () => {
    const states = new StateBuffers()
    states.setStyle('nodes', 2, { outline: 7, outlineWidth: 3.5 })
    expect(states.paint[10]).toBe(7)
    expect(new Float32Array(states.paint.buffer, 11 * 4, 1)[0]).toBe(3.5)
    states.setStyle('nodes', 2, { opacity: 1 })
    expect(states.paint[10]).toBe(noPaint)
    expect(states.paint[11]).toBe(noPaint)
  })

  it('writes the label color of a state', () => {
    const states = new StateBuffers()
    states.setStyle('nodes', 1, { labelColor: 12 })
    expect(states.labels[4]).toBe(12)
    states.setStyle('edges', 0, { labelColor: 3 })
    expect(states.labels[32 * 4]).toBe(3)
    states.setStyle('nodes', 1, null)
    expect(states.labels[4]).toBe(noPaint)
  })

  it('keeps edge styles in their own table', () => {
    const states = new StateBuffers()
    states.setStyle('edges', 1, { strokeWidth: 3, label: false, stroke: 4 })
    expect(states.numbers[(32 + 1) * 4 + 1]).toBe(3)
    expect(states.paint[(32 + 1) * 4 + 1]).toBe(4)
    expect(states.numbers[4 + 1]).toBe(-1)
    expect(states.labelFlags[1]).toBe(-1)
    expect(states.edgeLabelFlags[1]).toBe(0)
  })

  it('versions the highlighted lists', () => {
    const states = new StateBuffers()
    states.setHighlighted([1, 2], [0])
    expect(states.highlightedNodes).toEqual([1, 2])
    expect(states.highlightVersion).toBe(1)
  })

  it('writes the look of the others in a second row of each table', () => {
    const states = new StateBuffers()
    states.setStyle('nodes', 4, { stroke: 2 }, { opacity: 0.2, label: false })
    states.setStyle('edges', 4, null, { opacity: 0.3 })
    const nodeRow = stateRow('nodes', 4, false)
    const edgeRow = stateRow('edges', 4, false)
    expect(nodeRow).toBe(64 + 4)
    expect(edgeRow).toBe(96 + 4)
    expect(states.numbers[nodeRow * 4]).toBeCloseTo(0.2, 5)
    expect(states.numbers[edgeRow * 4]).toBeCloseTo(0.3, 5)
    expect(states.paint[stateRow('nodes', 4, true) * 4 + 1]).toBe(2)
    expect(states.labelFlags[32 + 4]).toBe(0)
    expect(states.labelFlags[4]).toBe(-1)
  })

  it('applies the others only while the state has a member of any kind', () => {
    const states = new StateBuffers()
    states.reserve(4, 4)
    states.setStyle('nodes', 3, null, { opacity: 0.2 })
    states.setStyle('edges', 3, null, { opacity: 0.2 })
    expect(states.others('nodes')).toBe(0)
    const version = states.tableVersion
    states.setEdge(1, 1 << 3)
    expect(states.others('nodes')).toBe(1 << 3)
    expect(states.others('edges')).toBe(1 << 3)
    expect(states.tableVersion).toBe(version + 1)
    states.setNode(2, 1 << 3)
    expect(states.tableVersion).toBe(version + 1)
    states.setEdge(1, 0)
    expect(states.others('nodes')).toBe(1 << 3)
    states.setNode(2, 0)
    expect(states.others('nodes')).toBe(0)
    expect(states.tableVersion).toBe(version + 2)
  })

  it('leaves the table alone when a state without others gains members', () => {
    const states = new StateBuffers()
    states.setStyle('nodes', 5, { opacity: 0.5 })
    const version = states.tableVersion
    states.setNode(0, 1 << 5)
    expect(states.active).toBe(1 << 5)
    expect(states.tableVersion).toBe(version)
  })

  it('hides the others of an active state through the hide filter', () => {
    const states = new StateBuffers()
    states.reserve(3, 3)
    states.setStyle('nodes', 3, null, { hide: true })
    expect(states.hide).toBeNull()
    states.setNode(1, 1 << 3)
    const filter = states.hide
    expect(filter?.otherNodes).toBe(1 << 3)
    expect(filter?.otherEdges).toBe(0)
    states.setNode(1, 0)
    expect(states.hide).toBeNull()
  })

  it('marks the always labels of members and of others', () => {
    const states = new StateBuffers()
    states.setStyle('nodes', 6, { label: 'always' }, { label: 'always' })
    expect(states.nodeAlways).toBe(1 << 6)
    expect(states.labelFlags[6]).toBe(2)
    expect(states.labelFlags[32 + 6]).toBe(2)
    expect(states.numbers[stateRow('nodes', 6, true) * 4 + 3]).toBe(2)
    expect(states.othersAlways('nodes')).toBe(0)
    states.setNode(0, 1 << 6)
    expect(states.othersAlways('nodes')).toBe(1 << 6)
  })

  it('keeps a mask per half of an edge and falls back to the whole mask', () => {
    const states = new StateBuffers()
    states.reserve(2, 4)
    states.setEdge(1, 0b11)
    states.edgeDirty.take()
    expect(states.halfMask(1, 'source')).toBe(0b11)
    states.setEdgeHalves(1, 0b10, 0b01)
    expect(states.halfMask(1, 'source')).toBe(0b10)
    expect(states.halfMask(1, 'target')).toBe(0b01)
    expect(states.halvesCount).toBe(1)
    expect(states.edgeDirty.take()).toEqual([1, 1])
    states.setEdgeHalves(1, 0b10, 0b01)
    expect(states.edgeDirty.take()).toBeNull()
    const copy = states.copy()
    states.clearEdgeHalves(1)
    expect(states.halfMask(1, 'target')).toBe(0b11)
    expect(states.halvesCount).toBe(0)
    expect(copy.halfMask(1, 'target')).toBe(0b01)
  })

  it('turns the hide filter on while a half alone is hidden', () => {
    const states = new StateBuffers()
    states.reserve(2, 2)
    states.setStyle('edges', 4, { hide: true })
    states.setEdgeHalves(0, 0, 0)
    expect(states.hide).toBeNull()
    states.setEdgeHalves(0, 1 << 4, 0)
    expect(states.hide?.edges).toBe(1 << 4)
    states.setEdgeHalves(0, 0, 0)
    expect(states.hide).toBeNull()
    states.setEdgeHalves(0, 0, 1 << 4)
    states.clearEdgeHalves(0)
    expect(states.hide).toBeNull()
  })

  it('copies tables, masks and member counts', () => {
    const states = new StateBuffers()
    states.setStyle('edges', 3, { stroke: 4 }, { opacity: 0.2, hide: true, flow: 40 })
    states.setEdge(2, 1 << 3)
    states.setAlways([1], [2])
    const copy = states.copy()
    expect(copy.others('edges')).toBe(1 << 3)
    expect(copy.othersFlow()).toBe(1 << 3)
    expect(copy.hide?.otherEdges).toBe(1 << 3)
    expect(copy.edgeMask[2]).toBe(1 << 3)
    expect(copy.alwaysEdges).toEqual([2])
    copy.setEdge(2, 0)
    expect(copy.others('edges')).toBe(0)
    expect(states.others('edges')).toBe(1 << 3)
  })
})
